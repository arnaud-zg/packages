#!/usr/bin/env node
// One issue form per public package, so the form a reporter picks labels the issue: no CI needed.
// `node scripts/sync-issues.mjs` writes the forms; `--labels` also syncs the repo's labels (dry run
// unless `--apply`).
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, ".github/ISSUE_TEMPLATE");
const args = new Set(process.argv.slice(2));

const packages = fs
  .readdirSync(path.join(root, "packages"))
  .map((folder) => ({ folder, file: path.join(root, "packages", folder, "package.json") }))
  .filter(({ file }) => fs.existsSync(file))
  .map(({ folder, file }) => ({ folder, ...JSON.parse(fs.readFileSync(file, "utf8")) }))
  .filter((pkg) => !pkg.private)
  .sort((a, b) => a.name.localeCompare(b.name));

const PRIORITIES = [
  ["priority: high", "b60205", "Do next: unblocks users or several packages"],
  ["priority: medium", "fbca04", "Worth doing, no rush"],
  ["priority: low", "c5def5", "Low value: a pull request is welcome, or it closes"],
];
const RETIRED = ["duplicate", "invalid", "wontfix", "question", "help wanted"];

const quote = (text) => JSON.stringify(text);
const form = (
  name,
  about,
  labels,
) => `# Generated by scripts/sync-issues.mjs: edit the script, not this file.
name: ${quote(name)}
description: ${quote(about)}
labels: [${labels.map(quote).join(", ")}]
body:
  - type: textarea
    id: what
    attributes:
      label: What happened, or what do you want?
      description: A bug, an idea or a question. One sentence is enough to start.
    validations:
      required: true
  - type: textarea
    id: repro
    attributes:
      label: How to reproduce
      description: Optional. Commands, a config snippet, versions (\`npx <package> --version\`, \`node -v\`).
      render: shell
`;

fs.mkdirSync(dir, { recursive: true });
for (const file of fs.readdirSync(dir)) {
  if (file.endsWith(".yml") && file !== "config.yml") fs.rmSync(path.join(dir, file));
}
for (const pkg of packages) {
  const about = (pkg.description ?? "").split(/(?<=\.) /)[0];
  fs.writeFileSync(
    path.join(dir, `${pkg.folder}.yml`),
    form(pkg.name, about, [`pkg: ${pkg.name}`]),
  );
}
fs.writeFileSync(
  path.join(dir, "zz-not-sure.yml"),
  form("Not sure which package", "Anything else: the repository, the docs, or you don't know.", []),
);
fs.writeFileSync(path.join(dir, "config.yml"), "blank_issues_enabled: false\n");
console.log(`wrote ${packages.length + 1} issue forms`);

if (args.has("--labels")) {
  const apply = args.has("--apply");
  const gh = (...cmd) =>
    apply ? execFileSync("gh", cmd, { stdio: "inherit" }) : console.log("gh", ...cmd);
  const existing = new Set(
    JSON.parse(
      execFileSync("gh", ["label", "list", "--limit", "200", "--json", "name"], {
        encoding: "utf8",
      }),
    ).map(({ name }) => name),
  );
  const wanted = [
    ...packages.map((pkg) => [`pkg: ${pkg.name}`, "1d76db", (pkg.description ?? "").slice(0, 100)]),
    ...PRIORITIES,
  ];
  for (const [name, color, description] of wanted) {
    gh(
      "label",
      existing.has(name) ? "edit" : "create",
      name,
      "--color",
      color,
      "--description",
      description,
    );
  }
  for (const name of RETIRED.filter((name) => existing.has(name)))
    gh("label", "delete", name, "--yes");
  const stale = [...existing].filter(
    (name) => name.startsWith("pkg: ") && !wanted.some(([w]) => w === name),
  );
  for (const name of stale) gh("label", "delete", name, "--yes");
  if (!apply) console.log("dry run: add --apply to change the labels");
}
